"""T23: Morphogen on a machine of its own, end to end through morphogen/deploy/local.py, on a throwaway instance
(its own MORPHOGEN_HOME, container, volume and ports).

  up        Postgres in Docker, the record and modules installed, the services, the compose runner and the UI
  person    a person signs in to the UI with their own password
  agent     an agent gets its own login, and describes a one-service system quoting a recorded conversation
  propose   the compose file waits in the review lane
  approve   the person approves it over the UI's MCP endpoint; the intent actuator commits it to the instance's
            own intent repository, and the compose runner starts the system (a Redis already pulled for G3)
  down      every process stops

  python3 morphogen/tests/test_local.py   (needs Docker, psql, gitleaks; KK_REQUIRE_DOCKER=1 makes Docker required)
"""
import json
import os
import secrets
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCAL = ROOT / "morphogen" / "deploy" / "local.py"
sys.path[:0] = [str(ROOT / "kernel" / "src")]
REDIS = next(x.split("image:", 1)[1].strip() for x in (ROOT / "morphogen" / "intent" / "systems" / "podinfo" / "compose.yaml")
             .read_text().splitlines() if "image: redis" in x)
KKT = "https://w3id.org/knowledge-kernel/tosca#"
RDF_TYPE, LABEL = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type", "http://www.w3.org/2000/01/rdf-schema#label"
MAX, PROP = "https://www.irit.fr/recherches/MELODI/ontologies/BBO#maxValue", "http://www.w3.org/ns/sosa/observedProperty"


def check(cond, msg):
    if not cond:
        raise SystemExit(f"CHECK FAILED: {msg}")
    print(f"ok: {msg}", flush=True)


def wait(what, f, timeout=180, every=1.0):
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        if got := f():
            return got
        time.sleep(every)
    raise SystemExit(f"CHECK FAILED: timed out waiting for {what}")


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def post(url, body, token=None):
    req = urllib.request.Request(url, json.dumps(body).encode(), {"Content-Type": "application/json",
                                 "Accept": "application/json, text/event-stream", **({"Authorization": f"Bearer {token}"} if token else {})})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.status, json.loads(r.read() or b"null")
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read() or b"null")


if subprocess.run(["docker", "info"], capture_output=True).returncode != 0:
    if os.environ.get("KK_REQUIRE_DOCKER") == "1":
        raise SystemExit("CHECK FAILED: KK_REQUIRE_DOCKER=1 and no Docker daemon answers")
    print("skipped: no Docker daemon")
    sys.exit(0)

home = Path(tempfile.mkdtemp(prefix="kk-local-"))
home.chmod(0o755)                                  # `up` makes it yours alone
instance = f"kk-local-test-{os.getpid()}"
s = {"instance": instance, "db_port": free_port(), "ui_port": free_port(), "otlp_port": free_port()}   # up adds the secrets
(home / "secrets.json").write_text(json.dumps(s))
(home / "secrets.json").chmod(0o600)
env = {k: v for k, v in os.environ.items() if not k.startswith("PG")}
env["MORPHOGEN_HOME"] = str(home)


def local(*args, stdin=None):
    return subprocess.run([sys.executable, str(LOCAL), *args], env=env, input=stdin, capture_output=True, text=True, timeout=600)


try:
    out = local("up")
    print(out.stdout.strip())
    check(out.returncode == 0 and "Morphogen is up" in out.stdout, f"up: the record, the services and the UI ({out.stderr.strip()[-600:]})")
    s = json.loads((home / "secrets.json").read_text())
    mode = lambda f: f.stat().st_mode & 0o777  # noqa: E731
    check(mode(home) == 0o700 and mode(home / "secrets.json") == 0o600 and {"superuser", "logins", "jwt", "otlp"} <= set(s)
          and not (home / "pg-password").exists(),
          "secrets: generated by up, MORPHOGEN_HOME yours alone (0700), secrets.json 0600, the init password file gone")
    ui = f"http://127.0.0.1:{s['ui_port']}"
    def answers():
        try:
            return urllib.request.urlopen(ui + "/ui/", timeout=2).status == 200
        except OSError:
            return False
    wait("the UI", answers, timeout=60)
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as u:     # this machine's address on its network
        u.connect(("10.255.255.255", 1))
        lan = u.getsockname()[0]
    def reaches(host):
        try:
            with socket.create_connection((host, s["ui_port"]), timeout=2):
                return True
        except OSError:
            return False
    check(lan != "127.0.0.1" and not reaches(lan), f"the UI listens on 127.0.0.1 only, not on {lan}")
    st = local("status").stdout
    check(all(f"{p}: running" in st for p in ("reconcile", "observer-otel", "compose", "ui")), "status: every process runs")
    sys.path.insert(0, str(LOCAL.parent))
    from local import SERVICES
    rec = lambda: [json.loads(x) for x in (home / "logs" / "reconcile.log").read_text().splitlines() if x.startswith("{")]  # noqa: E731
    wait("the reconciler to start every service", lambda: set(SERVICES) <= {e.get("provider") for e in rec() if e.get("event") == "started"},
         timeout=60)
    time.sleep(12)                                 # a crash-looping service would exit and restart by now
    bad = [e for e in rec() if e.get("event") in ("exited", "restarting", "failed", "refused")]
    check(not bad, f"the reconciler runs every service of the local environment from intent, none exiting ({len(SERVICES)}; {bad[:2]})")
    import psycopg
    SVC = SERVICES
    su_url = f"host=127.0.0.1 port={s['db_port']} dbname=morphogen user=postgres password={s['superuser']}"
    logins_in_use = {r[0] for r in psycopg.connect(su_url, autocommit=True).execute(
        "select distinct usename from pg_stat_activity where datname = 'morphogen'").fetchall()}
    want = {(json.loads((home / "service-logins.json").read_text()).get(n) or [None, f"{SVC[n][3]}_login"])[1] for n in SVC}
    check(want <= logins_in_use, f"every service connects as its own login ({sorted(want - logins_in_use)} missing)")
    os.environ["KK_LOGIN_SECRET"] = s["logins"]
    sys.path.insert(0, str(ROOT / "morphogen" / "src"))
    from morphogen.logins import password_for
    derived = [password_for(r[0]) for r in psycopg.connect(su_url, autocommit=True).execute(
        "select rolname from pg_roles where rolname like 'kkm%login'").fetchall()]
    del os.environ["KK_LOGIN_SECRET"]
    secret_values = [s["superuser"], s["logins"], s["otlp"], s["jwt"], s["authenticator"], *derived]
    leaked = [f.name for f in (home / "logs").iterdir() if any(v in f.read_text() for v in secret_values)]
    check(not leaked, f"no secret in any log ({leaked})")

    password = secrets.token_urlsafe(16)
    out = local("person", "alice", stdin=password + "\n")
    check(out.returncode == 0, f"person: alice is added ({out.stderr.strip()[-300:]})")
    code, body = post(ui + "/ui/login", {"name": "alice", "password": password})
    check(code == 200 and body.get("token"), "alice signs in to the UI with her own password")
    token = body["token"]

    out = local("agent", "interviewer")
    check(out.returncode == 0, f"agent: the interviewer gets its own login ({out.stderr.strip()[-300:]})")
    url = json.loads((home / "mcp" / "interviewer.json").read_text())["mcpServers"]["morphogen"]["env"]["KK_DATABASE_URL"]
    check("postgres" not in url and "kk_authenticator" not in url and mode(home / "mcp" / "interviewer.json") == 0o600,
          "the agent's MCP config holds its own login, nothing more, readable by you alone")

    messages = [("1", "interviewer", "What system would you like Morphogen to run?"),
                ("2", "Alice", f"A cache: one Redis service, {REDIS}."),
                ("3", "interviewer", "How slow may it get before something should change?"),
                ("4", "Alice", "Requests to the cache should stay within 50 ms on average.")]
    chat = home / "cache.jsonl"
    chat.write_text("".join(json.dumps({"id": i, "conversation": "cache-intake", "author": a, "time": f"2026-11-01T09:0{i}:00Z",
                                        "text": t, **({"kind": "agent"} if a == "interviewer" else {})}) + "\n"
                            for i, a, t in messages))
    out = local("record", str(chat), "--source", "cache")
    check(out.returncode == 0, f"record: the conversation is stored as notes ({out.stderr.strip()[-300:]})")

    from kk.lib import connect, run, submit
    m = lambda i: f"urn:kk:message:cache:cache-intake:{i}"  # noqa: E731
    node, system = "urn:kk:node:cache:redis", "urn:kk:system:cache"

    def claim(subj, pred, obj, quote, msg, q=None):
        c = {"op": "add_claim", "subject": subj, "predicate": pred, "object": obj, "evidence_type": "extracted",
             "references": [{"source_uri": m(msg), "quote": quote}]}
        return {**c, "qualifiers": q} if q else c
    ops = [claim(system, RDF_TYPE, {"entity": KKT + "ServiceTemplate"}, "A cache", "2"),
           claim(system, LABEL, {"value": {"@value": "cache"}}, "A cache", "2"),
           claim(node, RDF_TYPE, {"entity": KKT + "NodeTemplate"}, "one Redis service", "2"),
           claim(node, LABEL, {"value": {"@value": "redis"}}, "Redis", "2"),
           claim(node, KKT + "memberOf", {"entity": system}, "A cache: one Redis service", "2"),
           claim(node, KKT + "propertyValue", {"value": {"@value": REDIS}}, REDIS, "2", {KKT + "propertyName": "image"}),
           claim(node, MAX, {"value": {"@value": 0.05}}, "within 50 ms on average", "4", {PROP: "urn:kk:property:latency-seconds-mean"})]
    with connect(url=url) as me, me.cursor() as cur, run(cur, "urn:kk:module:interviewer") as (rid, _):
        res = submit(cur, {"idempotency_key": "cache:describe", "attributed_to": "urn:kk:agent:interviewer",
                           "target_scope": "urn:kk:scope:default", "ops": ops}, rid)
    with connect(url=url) as me:
        st = wait("the description to apply", lambda: (r := me.execute("select status from api.change_sets where id = %s",
                                                                       (res["id"],)).fetchone()) and r[0] in ("applied", "invalid") and r[0])
    check(st == "applied", f"the agent's description applies (the validator runs under the reconciler) ({st})")

    out = wait("a proposal", lambda: (o := local("propose", "cache")).returncode == 0 and o, timeout=120, every=5)
    plan = json.loads(out.stdout.strip().splitlines()[0])
    check(REDIS in plan["text"], "propose: the compose file waits in the review lane")

    # Neither the agent nor a service can approve as a person (invariants 4 and 5).
    os.environ["KK_LOGIN_SECRET"] = s["logins"]
    planner = f"host=127.0.0.1 port={s['db_port']} dbname=morphogen user=kkm_planner_login password={password_for('kkm_planner_login')}"
    del os.environ["KK_LOGIN_SECRET"]
    for who, conn_url in (("the agent", url), ("the planner's login", planner)):
        for attempt in ("select api.review(%s::uuid, true, 'mine')", "set role person_alice", "set role kk_reviewer",
                        "set role kkm_prediction_verifier"):
            with psycopg.connect(conn_url, autocommit=True) as c:
                try:
                    c.execute(attempt, (plan["change_set"],) if "%s" in attempt else ())
                    ok = False
                except psycopg.Error as e:
                    ok = e.sqlstate == "42501"              # refused for want of privilege, nothing else
            check(ok, f"{who} cannot: {attempt.split('(')[0].replace('select ', '')}")
    code, body = post(ui + "/mcp", {"jsonrpc": "2.0", "id": 1, "method": "tools/call",
                                    "params": {"name": "review", "arguments": {"change_set_id": plan["change_set"], "approve": True,
                                                                               "note": "run it"}}}, token)
    check(code == 200 and not body["result"].get("isError"), f"approve: alice approves it in the UI ({body})")
    repo = home / "intent"
    show = lambda: subprocess.run(["git", "-C", str(repo), "show", "HEAD:systems/cache/compose.yaml"], capture_output=True, text=True)  # noqa: E731
    wait("the intent actuator to commit the file", lambda: show().returncode == 0, timeout=120)
    check(show().stdout == plan["text"], "write: the approved text, committed to the instance's own intent repository")
    events = lambda: [json.loads(x) for x in (home / "logs" / "compose.log").read_text().splitlines() if x.startswith("{")]  # noqa: E731
    e = wait("the system to start", lambda: [x for x in events() if x.get("system") == "cache" and x["event"] in ("started", "failed")],
             timeout=300)
    check(e[0]["event"] == "started" and e[0]["project"] == "kk-cache", f"run: the compose runner starts the approved system ({e[0]})")

    # Stopped and started again, Postgres included (as after a reboot): everything comes back, the record kept.
    out = local("down", "--db")
    check(out.returncode == 0, "down --db: the processes and Postgres stop")
    out = local("up")
    check(out.returncode == 0 and "Morphogen is up" in out.stdout, f"up again: Postgres restarts from its volume ({out.stderr.strip()[-400:]})")
    check(not (home / "pg-password").exists(), "the init password file is gone again once Postgres answers")
    st = local("status").stdout
    check(all(f"{p}: running" in st for p in ("reconcile", "observer-otel", "compose", "ui")), "status: every process runs again")
    code, body = post(ui + "/ui/login", {"name": "alice", "password": password})
    check(code == 200 and body.get("token"), "the record is kept: alice signs in again")
finally:
    pids = json.loads((home / "pids.json").read_text()) if (home / "pids.json").exists() else {}
    out = local("down", "--db")
    print(out.stdout.strip())
    subprocess.run(["docker", "compose", "-p", "kk-cache", "down", "-v", "-t", "1"], capture_output=True)
    subprocess.run(["docker", "rm", "-f", f"{instance}-postgres"], capture_output=True)
    subprocess.run(["docker", "volume", "rm", f"{instance}-pgdata"], capture_output=True)
    shutil.rmtree(home, ignore_errors=True)
def gone(pid):
    try:
        os.kill(pid, 0)
        return False
    except ProcessLookupError:
        return True
check(pids and wait("the processes to stop", lambda: all(gone(p["pid"]) for p in pids.values()), timeout=30), "down: every process stops")
print("local bring-up test passed")
