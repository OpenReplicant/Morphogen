"""Cut a pack file from an upstream vocabulary: only the terms this platform uses, each with the triples upstream
says about it, minus anything in a namespace the packs do not carry (e.g. LinkML's own modelling terms).

  python3 scripts/vocab_subset.py UPSTREAM_FILE --url URL --version V --license L --title T \
      --ns PREFIX=IRI --drop-ns IRI ... TERM ... > kernel/packs/<id>.ttl

The header records the upstream URL, version and sha256, so a reviewer can fetch and compare. Regenerate, don't edit.
"""
import argparse
import hashlib
import sys

import rdflib
from rdflib import URIRef


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("upstream")
    ap.add_argument("terms", nargs="+", help="local names in --ns")
    ap.add_argument("--url", required=True)
    ap.add_argument("--version", required=True)
    ap.add_argument("--license", required=True)
    ap.add_argument("--title", required=True)
    ap.add_argument("--ns", required=True, help="PREFIX=IRI of the terms")
    ap.add_argument("--drop-ns", action="append", default=[], help="drop triples whose predicate or object is in it")
    ap.add_argument("--revision", default="1")
    ap.add_argument("--ontology", help="the ontology's IRI (default: the namespace without its last # or /)")
    a = ap.parse_args()
    data = open(a.upstream, "rb").read()
    src = rdflib.Graph().parse(data=data, format="turtle")
    prefix, ns = a.ns.split("=", 1)
    out = rdflib.Graph()
    out.bind(prefix, ns)
    for p, iri in src.namespaces():
        if not any(str(iri).startswith(d) for d in a.drop_ns):
            out.bind(p, iri)
    for t in a.terms:
        s = URIRef(ns + t)
        found = False
        for _, p, o in src.triples((s, None, None)):
            found = True
            if any(str(x).startswith(d) for x in (p, o) for d in a.drop_ns) or isinstance(o, rdflib.BNode):
                continue
            out.add((s, p, o))
        if not found:
            raise SystemExit(f"{t}: not in {a.upstream}")
    onto = URIRef(a.ontology or ns.rstrip("#/"))
    out.add((onto, rdflib.RDF.type, rdflib.OWL.Ontology))
    out.add((onto, rdflib.RDFS.label, rdflib.Literal(a.title)))
    out.add((onto, rdflib.DCTERMS.license, URIRef(a.license)))
    out.add((onto, rdflib.DCTERMS.source, URIRef(a.url)))
    out.add((onto, rdflib.OWL.versionInfo, rdflib.Literal(f"{a.version}+s{a.revision}")))
    out.bind("dcterms", rdflib.DCTERMS)
    head = (f"# {a.title}: the subset of terms this platform uses (generated by scripts/vocab_subset.py;\n"
            f"# regenerate, don't edit). Upstream {a.url} version {a.version}, sha256 {hashlib.sha256(data).hexdigest()}; "
            f"subset revision {a.revision}.\n# License {a.license}. Terms: {' '.join(a.terms)}\n\n")
    sys.stdout.write(head + out.serialize(format="turtle"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
